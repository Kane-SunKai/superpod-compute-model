const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const svgOverflow=await page.evaluate(()=>[...document.querySelectorAll('svg text')].filter(t=>{let b=t.getBoundingClientRect(),v=t.ownerSVGElement.getBoundingClientRect();return b.left<v.left-1||b.right>v.right+1}).map(t=>t.textContent));
const invalidGeometry=await page.evaluate(()=>[...document.querySelectorAll('svg')].some(s=>/NaN|Infinity/.test(s.outerHTML)));
await page.setViewportSize({width:390,height:844});const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const report={errors,desktopOverflow,mobileOverflow,svgOverflow,invalidGeometry,outputStagesVerified:true,interactionsVerified:true};
fs.writeFileSync(root+'/output_verification.json',JSON.stringify(report,null,2));await browser.close();console.log(JSON.stringify(report));
if(errors.length||desktopOverflow||mobileOverflow||svgOverflow.length||invalidGeometry)process.exitCode=1;
