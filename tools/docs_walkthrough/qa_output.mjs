import {pathToFileURL,fileURLToPath} from 'node:url';
import fs from 'node:fs';
const require=createRequire('C:/Users/sunkai/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json');
const {chromium}=require('playwright');
const root=process.argv[2] || fileURLToPath(new URL('.',import.meta.url));
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(root+'/单卡计算建模_总体方案与流水线.html').href);
await page.waitForSelector('#mainTimeline svg');
for(const id of ['mainTimeline','outputTimeline','reuseTimeline','overview'])await page.locator('#'+id).screenshot({path:root+'/'+id+'_v32.png'});
await page.locator('#panel').selectOption('63');
if(!await page.locator('#panelDetail').innerText().then(s=>s.includes('面板 63')))throw Error('panel interaction broken');
await page.locator('#reuseOff').click();await page.locator('#reuseOn').click();
if(!await page.locator('#reuseTimeline').innerText().then(s=>s.includes('C寄存器')&&s.includes('仅搬新')))throw Error('reuse/write stage missing');
const tokens=await page.locator('#outputTimeline').innerText();
if(!tokens.includes('Shared')||!tokens.includes('L2')||!tokens.includes('不单独计时'))throw Error('output stages missing');
await page.locator('#tileR').selectOption('11');await page.locator('#tileC').selectOption('5');await page.locator('#tileK').selectOption('63');
